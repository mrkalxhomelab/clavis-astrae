// Regenerates assets.js: the list of files the service worker caches and the
// version string. Run after changing any app file:  node tools/build_assets.mjs 1.0.1
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const version = process.argv[2] || JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const include = ['index.html', 'manifest.webmanifest', 'assets.js', 'css', 'fonts', 'icons', 'src', 'vendor'];
const skip = (p) => /\.(md|LICENSE)$/i.test(p) || p.endsWith('.LICENSE');

const files = [];
function walk(p) {
  const s = statSync(p);
  if (s.isDirectory()) for (const f of readdirSync(p)) walk(join(p, f));
  else if (!skip(p)) files.push('./' + relative(root, p).split('\\').join('/'));
}
for (const i of include) walk(join(root, i));
files.sort();

writeFileSync(join(root, 'assets.js'),
  `// Generated by tools/build_assets.mjs. Do not edit by hand.\n` +
  `self.CLAVIS_VERSION = ${JSON.stringify(version)};\n` +
  `self.CLAVIS_ASSETS = ${JSON.stringify(files, null, 1)};\n`);
console.log(`assets.js: version ${version}, ${files.length} files`);
